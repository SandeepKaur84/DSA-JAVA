package Bit_Manipulation;

public class Operators {
    public static void main(String[] args) {
        System.out.println("Bitwise AND : " + (5 & 6));
        System.out.println("Bitwise OR : " + (5 | 6));
        System.out.println("Bitwise XOR : " + (5 ^ 6));
        System.out.println("Bitwise One's complement : " + (~5));
        System.out.println("Bitwise Left Shift : " + (5 << 2));
        System.out.println("Bitwise Right Shift : " + (6 >> 1));
    }
}
